-- Query 1: Show the total number of pets in the system.
select count(pet_id) as number_of_pets from pets;

-- Query 2: Show the average weight of pets for each species.
-- Display the species and average weight.
select species, avg(weight_kg)::decimal(5,2) as ave_of_weights from pets group by species;

-- Query 3: Show the total number of appointments for each veterinarian.
-- Display the veterinarian's full name and appointment count.
select CONCAT(v.first_name,' ',v.last_name) as veterinarian_full_name, count(va.appointment_id) as num_of_appointments
from veterinarians v inner join vet_appointments va on v.veterinarian_id = va.veterinarian_id
group by v.veterinarian_id, v.first_name, v.last_name;  --possible to write: CONCAT(v.first_name,' ',v.last_name)

-- Query 4: Show the total revenue generated by each product.
-- Calculate revenue using quantity multiplied by unit price.
-- Display the product name and total revenue.
select p.name as product_name, sum(oi.quantity*oi.unit_price) as total_revenue
from products p inner join order_items oi on oi.product_id = p.product_id
group by p.product_id, p.name;


-- Query 5: Show the minimum and maximum product price for each product category.
-- Display the category, minimum price, and maximum price.
select p.category, min(p.price) as minimum_price,max(p.price) as max_price
from products p group by p.category;

-- Query 6: Show product categories whose average price is greater than 40.
-- Display the category and average price.
select category, avg(price)::decimal(5,2) as ave_price from products group by category HAVING avg(price)>40;


-- Query 7: Show veterinarians who have completed more than 2 appointments.
-- Display the veterinarian's full name and number of completed appointments.
select CONCAT(v.first_name,' ',v.last_name) as veterinarian_full_name, count(va.appointment_id) as appointments_completed
from veterinarians v inner join vet_appointments va on v.veterinarian_id = va.veterinarian_id
where va.status = 'Completed' group by v.veterinarian_id, v.first_name, v.last_name having count(va.appointment_id)>2;

-- Query 8: Show each clinic together with the total number of appointments handled by its veterinarians.
-- Display the clinic name and appointment count.
select c.name as clinic_name, count(va.appointment_id) as num_of_appointments
from clinics c inner join veterinarians v on v.clinic_id = c.clinic_id inner join vet_appointments va on va.veterinarian_id = v.veterinarian_id
group by c.clinic_id,c.name;

-- Query 9: Show each customer together with the number of orders they placed and their total spending.
-- Include only customers who have placed at least 2 orders.
select o.user_id as customer_id, count(o.order_id) as number_of_orders, sum(o.total_amount) as total_spending
from orders o group by o.user_id having count(o.order_id)>=2 order by o.user_id;

-- Query 10: Show each product together with its total quantity sold and classify its sales performance.
-- Use CASE:
-- 100 or more units  → 'High Sales'
-- 50–99 units        → 'Medium Sales'
-- Less than 50       → 'Low Sales'

select p.name AS product_name,sum(oi.quantity) as total_quantity,
case 
	when sum(quantity)>=100 then 'High Sales'
	when sum(quantity)>=50 then 'Medium Sales'
	when sum(quantity)<50 then 'Low Sales'
end as Sales_Performance
from products p inner join order_items oi on p.product_id = oi.product_id
group by p.product_id,p.name order by total_quantity desc;

